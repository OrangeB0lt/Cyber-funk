/** Where the pages go. */
export const TABLES_DIR = path.join(import.meta.dirname, '..', 'docs', 'reference', 'tables');

/* ---------------- Markdown helpers ---------------- */

/** Cell text: lexicon links as their display text, no pipes or line breaks. */
const esc = (s: string) =>
  s
    .replace(/\[\[([^\]|]+)(?:\|([^\]]+))?\]\]/g, (_m, a: string, b?: string) => b || a)
    .replace(/\|/g, '\\|')
    .replace(/\s*\n\s*/g, ' ');
const code = (s: string) => `\`${s}\``;
const named = (name: string, id: string) => `${esc(name)} (${code(id)})`;
const pct = (n: number) => `${Math.round(n * 100)}%`;
const dash = (s: string | null | undefined) => (s ? s : '—');

function table(headers: string[], rows: string[][]): string {
  const line = (cells: string[]) => `| ${cells.join(' | ')} |`;
  return [line(headers), line(headers.map(() => '---')), ...rows.map(line)].join('\n');
}

function page(title: string, intro: string, sections: [string | null, string][]): string {
  const body = sections.map(([h, t]) => (h ? `## ${h}\n\n${t}` : t)).join('\n\n');
  return (
    `# ${title}\n\n` +
    `<!-- Generated by tools/reference.ts from src/content. Don't edit: run \`npm run docs:tables\`. -->\n\n` +
    `${intro}\n\n${body}\n`
  );
}

const stats = (b: StatBlock) =>
  Object.entries(b)
    .filter(([, v]) => v)
    .map(([k, v]) => `${v! > 0 ? '+' : ''}${v} ${STAT_NAMES[k as keyof typeof STAT_NAMES]}`)
    .join(', ');

const districtName = (d: DistrictId) => DISTRICTS[d].name;

/* ---------------- Pages ---------------- */

function enemies(): string {
  const sections: [string, string][] = [];
  for (const d of DISTRICT_IDS) {
    const ids = ENEMY_IDS.filter(id => ENEMIES[id].district === d);
    if (!ids.length) continue;
    const dd = DISTRICTS[d];
    const rows = ids.map(id => {
      const e = ENEMIES[id];
      const traits = [
        e.elite && 'elite',
        e.machine && 'machine',
        e.hologram && 'hologram',
        e.rival && `rival (${CLASSES[e.rival].name})`,
        e.pack && `pack of ${e.pack}`,
        e.hpMult && `Heart ×${e.hpMult}`,
        e.gritMult && `Grit ×${e.gritMult}`,
        e.dodgeBonus && `dodge +${pct(e.dodgeBonus)}`,
      ].filter(Boolean);
      const where = dd.pool.includes(id) ? 'streets' : dd.elite === id ? 'elite' : '—';
      const special = e.special === 'clone' ? 'your own skills' : e.special ? code(e.special) : '—';
      return [
        named(e.name, id),
        `${e.levels[0]}–${e.levels[1]}`,
        e.tone,
        e.weak,
        dash(e.resist),
        special,
        where,
        dash(traits.join(', ')),
      ];
    });
    sections.push([
      dd.name,
      table(['Enemy', 'Levels', 'Tone', 'Weak', 'Resists', 'Special', 'Spawns', 'Traits'], rows),
    ]);
  }
  return page(
    'Enemies',
    'Every enemy, by district. **Spawns**: in the street pool, as the district elite (bounties), or only from scenes (summons, rivals, ambushes).',
    sections,
  );
}

function bosses(): string {
  const rows = BOSS_IDS.map(id => {
    const b = BOSSES[id];
    const place = PLACE_IDS.find(p => PLACES[p].boss === id);
    const traits = [
      b.machine && 'machine',
      b.hologram && 'hologram',
      b.bluesTarget && 'only Play the Blues breaks its shield',
      b.hpMult && `Heart ×${b.hpMult}`,
    ].filter(Boolean);
    return [
      named(b.name, id),
      String(b.level),
      districtName(b.district),
      place ? named(PLACES[place].name, place) : 'the Tower climb',
      b.tone,
      b.weak,
      dash(b.resist),
      b.note ? NOTES[b.note].name : '—',
      b.next?.unlock ? districtName(b.next.unlock) : '—',
      dash(traits.join(', ')),
    ];
  });
  return page('Bosses', 'The eight bosses, in story order.', [
    [
      null,
      table(
        [
          'Boss',
          'Level',
          'District',
          'Fought at',
          'Tone',
          'Weak',
          'Resists',
          'Blue Note',
          'Unlocks',
          'Traits',
        ],
        rows,
      ),
    ],
  ]);
}

function skills(): string {
  const what = (id: SkillId) => esc(SKILLS[id].desc);
  const row = (slot: string, id: SkillId) => [
    slot,
    named(SKILLS[id].name, id),
    String(SKILLS[id].fp),
    what(id),
  ];
  const head = ['Unlock', 'Skill', 'Funk', 'What it does'];
  const sections: [string, string][] = CLASS_IDS.map(c => {
    const cl = CLASSES[c];
    const rows = [
      row('Riff', cl.riff),
      ...cl.skills.map((id, i) => row(`Level ${SKILL_LEVELS[i]}`, id)),
      row('Solo', cl.solo),
    ];
    return [`${cl.name} (${code(c)})`, table(head, rows)];
  });
  const usedBy = (id: SkillId) =>
    ENEMY_IDS.filter(e => ENEMIES[e].special === id)
      .map(e => ENEMIES[e].name)
      .join(', ');
  sections.push([
    'Enemy specials',
    table(
      ['Skill', 'Used by', 'What it does'],
      ENEMY_SKILL_IDS.map(id => [named(SKILLS[id].name, id), dash(usedBy(id)), what(id)]),
    ),
  ]);
  sections.push([
    'Boss moves',
    table(
      ['Skill', 'What it does'],
      BOSS_SKILL_IDS.map(id => [named(SKILLS[id].name, id), what(id)]),
    ),
  ]);
  sections.push([
    'Bandmate assists',
    table(
      ['Skill', 'Bandmate', 'What it does'],
      ASSIST_SKILL_IDS.map(id => {
        const mate = Object.values(BANDMATES).find(b => b.assist === id);
        return [named(SKILLS[id].name, id), mate ? mate.name : '—', what(id)];
      }),
    ),
  ]);
  return page(
    'Skills',
    'Each class plays its riff (free), six skills unlocked by level, and a solo. **Funk** is the cost.',
    sections,
  );
}

function statuses(): string {
  const rows = Object.values(STATUSES).map(s => [
    named(s.name, s.id),
    s.kind,
    s.untilTriggered ? 'until triggered' : String(s.turns),
    dash(
      Object.entries(s.mod ?? {})
        .map(([k, v]) => `${v > 0 ? '+' : ''}${pct(v)} ${STAT_NAMES[k as keyof typeof STAT_NAMES]}`)
        .join(', '),
    ),
    esc(s.desc),
  ]);
  return page('Statuses', 'Every status effect. **Turns** is the default duration.', [
    [null, table(['Status', 'Kind', 'Turns', 'Stat changes', 'What it does'], rows)],
  ]);
}

function items(): string {
  const use = (b: boolean) => (b ? 'yes' : '');
  const consumables = ITEM_IDS.filter(id => !ITEMS[id].key).map(id => {
    const it = ITEMS[id];
    const notes = [
      it.rare && 'rare',
      it.passive && 'works from the bag',
      it.revive && `revives at ${pct(it.revive.pct)} Heart`,
      it.prefight && `next fight: ${STATUSES[it.prefight.status].name}`,
      it.max && `carry ${it.max}`,
    ].filter(Boolean);
    return [
      named(it.name, id),
      it.price ? `Ð${it.price}` : '—',
      use(it.battle),
      use(it.field),
      dash(notes.join(', ')),
      esc(it.desc),
    ];
  });
  const keys = ITEM_IDS.filter(id => ITEMS[id].key).map(id => [
    named(ITEMS[id].name, id),
    esc(ITEMS[id].desc),
  ]);
  return page(
    'Items',
    'Consumables and key items. Shops sell at **Price** (before district modifiers) and buy back at 40%.',
    [
      ['Consumables', table(['Item', 'Price', 'Battle', 'Field', 'Notes', 'What it does'], consumables)],
      ['Key items', table(['Item', 'What it is'], keys)],
    ],
  );
}

function gear(): string {
  const extras = (g: GearDef) =>
    dash(
      [
        g.legendary && 'legendary',
        g.story && 'story reward',
        g.statusResist && `status resist ${pct(g.statusResist)}`,
        g.doubloonBonus && `Doubloons +${pct(g.doubloonBonus)}`,
        g.critBonus && `crit +${pct(g.critBonus)}`,
        g.oneZone && `wider On the One (+${pct(g.oneZone)})`,
        g.toneBonus &&
          Object.entries(g.toneBonus)
            .map(([t, v]) => `${t} +${pct(v)}`)
            .join(', '),
      ]
        .filter(Boolean)
        .join(', '),
    );
  const all = Object.values(GEAR);
  const rows = (list: GearDef[]) =>
    list.map(g => [
      named(g.name, g.id),
      String(g.level),
      g.price ? `Ð${g.price}` : '—',
      dash(stats(g.stats)),
      extras(g),
      esc(g.desc),
    ]);
  const head = ['Gear', 'Level', 'Price', 'Stats', 'Extras', 'Description'];
  const sections: [string, string][] = CLASS_IDS.map(c => [
    `${CLASSES[c].name} instruments`,
    table(
      head,
      rows(
        all
          .filter(g => g.slot === 'instrument' && g.cls === c)
          .sort((a, b) => INSTRUMENT_TIER_IDS.indexOf(a.tier!) - INSTRUMENT_TIER_IDS.indexOf(b.tier!)),
      ),
    ),
  ]);
  for (const [slot, title] of [
    ['threads', 'Threads'],
    ['charm', 'Charms'],
    ['mod', 'Mods'],
  ] as const)
    sections.push([title, table(head, rows(all.filter(g => g.slot === slot)))]);
  sections.push([
    'Sheet music',
    table(
      ['Technique', 'Price', 'What it does'],
      Object.values(SHEET_MUSIC).map(m => [named(m.name, m.id), `Ð${m.price}`, esc(m.desc)]),
    ),
  ]);
  return page(
    'Gear',
    'Instruments (one ladder per class), threads, charms, mods, and sheet music.',
    sections,
  );
}

function places(): string {
  const sections: [string, string][] = DISTRICT_IDS.map(d => {
    const rows = PLACE_IDS.filter(p => PLACES[p].district === d).map(p => {
      const pl = PLACES[p];
      return [named(pl.name, p), pl.boss ? BOSSES[pl.boss].name : '—', esc(pl.desc)];
    });
    return [districtName(d), table(['Place', 'Boss', 'Description'], rows)];
  });
  return page('Places', 'Every place, by district.', sections);
}

function quests(): string {
  const rows = QUEST_IDS.map(id => {
    const q = QUESTS[id];
    return [
      named(q.name, id),
      districtName(q.district),
      q.goal ? String(q.goal) : '—',
      esc(q.reward),
      String(q.xp),
      q.gold ? `Ð${q.gold}` : '—',
      esc(q.desc),
    ];
  });
  return page('Quests', 'Side quests. The logic lives in the scenes; this is what the journal shows.', [
    [null, table(['Quest', 'District', 'Goal', 'Reward', 'XP', 'Doubloons', 'Description'], rows)],
  ]);
}

/** Every page, by file name. */
export function generateTables(): Record<string, string> {
  const pages: [string, string, number][] = [
    ['enemies.md', enemies(), ENEMY_IDS.length],
    ['bosses.md', bosses(), BOSS_IDS.length],
    ['skills.md', skills(), Object.keys(SKILLS).length],
    ['statuses.md', statuses(), Object.keys(STATUSES).length],
    ['items.md', items(), ITEM_IDS.length],
    ['gear.md', gear(), Object.keys(GEAR).length + Object.keys(SHEET_MUSIC).length],
    ['places.md', places(), PLACE_IDS.length],
    ['quests.md', quests(), QUEST_IDS.length],
  ];
  const index = page(
    'Content tables',
    'The game content as tables, generated from `src/content`. For how content is defined, see [the content model](../../architecture/content-model.md).',
    [[null, pages.map(([f, , n]) => `- [${f.replace('.md', '')}](${f}) (${n})`).join('\n')]],
  );
  return Object.fromEntries([...pages.map(([f, text]) => [f, text]), ['README.md', index]]);
}

/** Pages that differ from what's on disk, are missing, or shouldn't be there. */
export function staleTables(pages: Record<string, string>): string[] {
  const onDisk = fs.existsSync(TABLES_DIR) ? fs.readdirSync(TABLES_DIR) : [];
  const stale = Object.entries(pages)
    .filter(([f, text]) => !onDisk.includes(f) || fs.readFileSync(path.join(TABLES_DIR, f), 'utf8') !== text)
    .map(([f]) => f);
  return [...stale, ...onDisk.filter(f => !(f in pages))];
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const pages = generateTables();
  fs.mkdirSync(TABLES_DIR, { recursive: true });
  for (const f of fs.readdirSync(TABLES_DIR)) if (!(f in pages)) fs.rmSync(path.join(TABLES_DIR, f));
  for (const [f, text] of Object.entries(pages)) fs.writeFileSync(path.join(TABLES_DIR, f), text);
  console.log(
    `tables: wrote ${Object.keys(pages).length} pages to ${path.relative(process.cwd(), TABLES_DIR)}/`,
  );
}
